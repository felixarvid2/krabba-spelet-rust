//! Hjälptexter för ? (HELP, SHOW_HELP och PARAM_HELP i ios.js, plus tilläggen längre ner i filen).
//! Tabellerna är genererade ur js/cli/ios.js (rad 6–74, 2308–2325 och 2457–2461); sena poster
//! ("om saknas") är redan ihopslagna med de första.

/// Hjälptext för ett nyckelord. in_show = raden börjar med show.
pub fn help_text(k: &str, in_show: bool) -> &'static str {
    if in_show {
        let h = show_help_map(k);
        if !h.is_empty() {
            return h;
        }
    }
    help_map(k)
}

/// Hjälp för parametertyper: ("A.B.C.D", "IP address") osv.
pub fn param_help(ty: &str) -> Option<(&'static str, &'static str)> {
    match ty {
        "ip" => Some(("A.B.C.D", "IP address")),
        "mask" => Some(("A.B.C.D", "Mask")),
        "wild" => Some(("A.B.C.D", "Wildcard bits")),
        "word" => Some(("WORD", "Name")),
        "text" => Some(("LINE", "Up to 240 characters describing this item")),
        "if" => Some(("GigabitEthernet", "GigabitEthernet IEEE 802.3z")),
        "vlist" => Some(("WORD", "VLAN IDs of the allowed VLANs when this port is in trunking mode")),
        "iphost" => Some(("WORD", "Ping destination address or hostname")),
        _ => None,
    }
}

